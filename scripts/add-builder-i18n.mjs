const LOCALES = ['es', 'fr', 'de', 'pt', 'zh', 'ja', 'ko', 'ar']
let updated = 0

for (const locale of LOCALES) {
  const filePath = join(I18N_DIR, `${locale}.json`)
  const raw = readFileSync(filePath, 'utf8')
  const parsed = JSON.parse(raw)

  if (parsed.builder && parsed.builder.titleAdvanced) {
    console.log(`↩︎  ${locale}.json already has the full builder section — skipped`)
    continue
  }

  parsed.builder = { ...BUILDER_SECTIONS[locale], ...parsed.builder, operations: { ...(parsed.builder?.operations ?? {}) } }
  // Match each file's existing indentation and line endings (all locale files use CRLF + 4 spaces).
  const indentMatch = raw.match(/\n(\s+)"/)
  const indent = indentMatch ? indentMatch[1].length : 4
  const eol = raw.includes('\r\n') ? '\r\n' : '\n'
  writeFileSync(filePath, JSON.stringify(parsed, null, indent).replace(/\n/g, eol) + eol, 'utf8')
  updated += 1
  console.log(`✓ ${locale}.json updated (${Object.keys(parsed.builder).length} builder keys)`)
}

console.log(`\nDone: ${updated} locale file(s) updated.`)
